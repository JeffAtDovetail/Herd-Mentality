const qrEl = document.getElementById('qr');
const joinUrlEl = document.getElementById('join-url');
const statusEl = document.getElementById('status');
const countEl = document.getElementById('count');
const emptyEl = document.getElementById('empty');
const playersEl = document.getElementById('players');

async function loadJoinInfo() {
  const res = await fetch('/api/info');
  const { joinUrl, qrSvg } = await res.json();
  qrEl.innerHTML = qrSvg; // SVG generated by our own server
  joinUrlEl.textContent = joinUrl;
}

function renderLobby(players) {
  const online = players.filter((p) => p.connected).length;
  countEl.textContent = String(online);
  emptyEl.hidden = players.length > 0;

  // Keep existing chips so only new players animate in.
  const existing = new Map([...playersEl.children].map((li) => [li.dataset.id, li]));
  const seen = new Set();

  for (const player of players) {
    seen.add(player.id);
    let li = existing.get(player.id);
    if (!li) {
      li = document.createElement('li');
      li.className = 'player';
      li.dataset.id = player.id;
      playersEl.append(li);
    }
    li.textContent = player.name; // textContent: names are user input
    li.classList.toggle('offline', !player.connected);
    li.title = player.connected ? 'Connected' : 'Disconnected';
  }

  for (const [id, li] of existing) {
    if (!seen.has(id)) li.remove();
  }
}

function connect() {
  const proto = location.protocol === 'https:' ? 'wss' : 'ws';
  const ws = new WebSocket(`${proto}://${location.host}/ws`);

  ws.addEventListener('open', () => {
    statusEl.textContent = 'Live';
    statusEl.classList.remove('error');
    ws.send(JSON.stringify({ type: 'host' }));
  });

  ws.addEventListener('message', (event) => {
    const msg = JSON.parse(event.data);
    if (msg.type === 'lobby') renderLobby(msg.players);
  });

  ws.addEventListener('close', () => {
    statusEl.textContent = 'Disconnected from server — retrying…';
    statusEl.classList.add('error');
    setTimeout(connect, 1500);
  });
}

loadJoinInfo().catch(() => {
  joinUrlEl.textContent = 'Could not load join link — is the server running?';
});
connect();
